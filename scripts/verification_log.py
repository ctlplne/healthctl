"""Generate docs/verification-log.md from the committed scorecard and corpus.

  python3 scripts/verification_log.py          # rewrite the log
  python3 scripts/verification_log.py --check  # fail if the log is stale

The numbers in the log come only from evaluation/release-fixture-results.json
and internal/clinical/testdata/corpus, so they can't drift from the evidence.
"""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SCORECARD = ROOT / "evaluation" / "release-fixture-results.json"
CORPUS = ROOT / "internal" / "clinical" / "testdata" / "corpus"
LOG = ROOT / "docs" / "verification-log.md"


def corpus_counts():
    counts = {}
    for path in sorted(CORPUS.glob("*.txt")):
        rows = [l for l in path.read_text().splitlines() if l.strip() and not l.lstrip().startswith("#")]
        counts[path.stem] = (len(rows), sum(1 for r in rows if r.startswith("warn")))
    return counts


def render():
    card = json.loads(SCORECARD.read_text())
    arms = card["scorecard"]["arms"]
    lines = [
        "# Verification log",
        "",
        "Generated by `python3 scripts/verification_log.py` from the committed release scorecard and the safety corpus. Do not edit by hand; `scripts/check_docs.py` fails when it is stale.",
        "",
        "All results use synthetic cases and the offline evaluation fixture, not a live model. A live-model baseline needs credentials and approval (see [HARDENING.md](../HARDENING.md), H3).",
        "",
        "## Release scorecard",
        "",
        f"Evaluation `{card['evaluationVersion']}`, mode `{card['mode']}`, {card['runs']} runs, {card['failedRuns']} failed.",
        "",
        "| Arm | Runs | Failed | Missed urgency checkpoints | Excessive urgency checkpoints | Key history found | Questions | Repeated questions |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in sorted(arms):
        a = arms[name]
        key = a["keyHistory"]
        lines.append(f"| {name.replace('_', ' ')} | {a['runs']} | {a['failed']} | {a['missedUrgencyCheckpoints']} | {a['excessiveUrgencyCheckpoints']} | {key['matched']} of {key['total']} | {a['questions']} | {a['repeatQuestions']} |")
    counts = corpus_counts()
    total = sum(n for n, _ in counts.values())
    warn = sum(w for _, w in counts.values())
    lines += [
        "",
        "## Safety corpus",
        "",
        f"{total} labeled synthetic sentences in {len(counts)} files, {warn} of which must raise a warning. `TestCorpus` fails CI on any missed urgent sentence.",
        "",
        "| File | Rows | Must warn |",
        "|---|---|---|",
    ]
    for stem, (n, w) in counts.items():
        lines.append(f"| `{stem}` | {n} | {w} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not LOG.exists() or LOG.read_text() != text:
            print("docs/verification-log.md is stale; run python3 scripts/verification_log.py")
            return 1
        return 0
    LOG.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
